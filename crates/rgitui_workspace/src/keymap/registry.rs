//! The command registry: one `commands!` declaration that defines every
//! rgitui command, its gpui action and its default key binding.
//!
//! # Key contexts
//!
//! `Workspace` is set on the workspace root element. The root adds `modal`
//! whenever an overlay or dialog is open, so `Workspace && !modal` is the
//! scope for shortcuts that must not fire while a modal is up — it replaces
//! the hand-rolled `any_overlay_active` gate for the commands listed here.
//! `TextInput` is set by [`rgitui_ui::TextInput`], so `!TextInput` keeps
//! unmodified single-key shortcuts from stealing typed characters.

// The `if <predicate>` clause of `commands!` resolves these by name at the
// invocation site; `always_show` is the default and is referenced through
// `$crate`, so it is not imported here.
use crate::command_palette::{
    has_changes, has_github_token, has_remotes, has_staged, has_stashes, in_progress_operation,
    is_bisecting, worktree_clean, CommandContext,
};

/// Static description of a single command.
///
/// Generated by `commands!`; see [`ALL_COMMANDS`].
pub struct CommandMeta {
    /// The command this metadata describes.
    pub id: CommandId,
    /// The view whose `commands!` block declared it. Groups the generated docs.
    pub view: &'static str,
    /// The gpui action namespace.
    pub namespace: &'static str,
    /// The full gpui action name, as written in `keymap.json`.
    pub action_name: &'static str,
    /// Default keystrokes. Empty when the command has no default binding.
    pub default_keystrokes: &'static [&'static str],
    /// Key context predicate the default bindings are scoped to.
    pub context: &'static str,
    /// Doc comment from the declaration. Leading whitespace is not trimmed.
    pub description: &'static str,
    /// Whether the command is offered in the command palette.
    pub in_palette: bool,
    /// Command-palette availability predicate.
    pub availability: fn(CommandContext) -> bool,
}

impl CommandMeta {
    /// The description with doc-comment padding removed.
    pub fn description(&self) -> &'static str {
        self.description.trim()
    }
}

commands! {
    view Workspace in rgitui context "Workspace && !modal" {
        /// Download objects and refs from the tracked remote.
        Fetch "secondary-shift-r" if has_remotes;
        /// Fetch from and integrate with the tracked remote branch.
        Pull unbound if has_remotes;
        /// Update the remote ref along with associated objects.
        Push unbound if has_remotes;
        /// Push every open repository.
        PushAll unbound if has_remotes;
        /// Pull every open repository.
        PullAll unbound if has_remotes;
        /// Overwrite the remote branch with the local one.
        ForcePush unbound if has_remotes;
        /// Commit the staged changes using the message in the commit panel.
        Commit "secondary-enter" if has_staged;
        /// Stage every change in the working tree.
        StageAll "secondary-s" if has_changes;
        /// Unstage everything currently staged.
        UnstageAll ["secondary-shift-s", "secondary-u"] if has_changes;
        /// Stash the working tree and index.
        StashSave "secondary-z" if has_changes;
        /// Apply the latest stash entry and drop it.
        StashPop "secondary-shift-z" if has_stashes;
        /// Apply the latest stash entry and keep it.
        StashApply unbound if has_stashes;
        /// Delete a stash entry.
        StashDrop unbound if has_stashes;
        /// Create a new branch.
        CreateBranch "secondary-b";
        /// Delete a branch.
        DeleteBranch unbound;
        /// Rename a branch.
        RenameBranch unbound;
        /// Merge another branch into the current one.
        MergeBranch unbound if worktree_clean;
        /// Create a tag.
        CreateTag unbound;
        /// Create a linked worktree.
        CreateWorktree unbound;
        /// Open a pull request for the current branch.
        CreatePr unbound if has_github_token;
        /// Cherry-pick a commit onto the current branch.
        CherryPick unbound if worktree_clean;
        /// Revert a commit.
        RevertCommit unbound if worktree_clean;
        /// Start an interactive rebase.
        InteractiveRebase unbound if worktree_clean;
        /// Discard every uncommitted change.
        DiscardAll unbound if has_changes;
        /// Delete untracked files.
        CleanUntracked unbound;
        /// Reset the working tree and index to HEAD.
        ResetHard unbound if has_changes;
        /// Abort the merge, rebase, cherry-pick or revert in progress.
        AbortOperation unbound if in_progress_operation;
        /// Continue the merge, rebase, cherry-pick or revert in progress.
        ContinueMerge unbound if in_progress_operation;
        /// Switch the diff viewer between unified and side-by-side.
        ToggleDiffMode unbound;
        /// Search the commit graph.
        Search unbound;
        /// Generate a commit message with the configured AI provider.
        AiMessage "secondary-g" if has_staged;
        /// Reload the repository state from disk.
        Refresh "f5";
        /// Open the settings window.
        Settings "secondary-," in "Workspace";
        /// Open the repository picker.
        OpenRepo "secondary-o" in "Workspace";
        /// Close every tab and return to the workspace home screen.
        WorkspaceHome "secondary-h";
        /// Reopen the most recently saved workspace.
        RestoreLastWorkspace unbound;
        /// Show the keyboard shortcut reference.
        Shortcuts "?" in "Workspace && !TextInput";
        /// Focus the sidebar to switch branches.
        SwitchBranch "secondary-shift-b";
        /// Blame the selected file.
        Blame unbound;
        /// Undo the last git operation.
        Undo unbound;
        /// Show the commit history of the selected file.
        FileHistory unbound;
        /// Show the reflog.
        Reflog unbound;
        /// Show the submodule list.
        Submodules unbound;
        /// Show the bisect log.
        Bisect unbound if is_bisecting;
        /// Start a bisect session.
        BisectStart unbound if worktree_clean;
        /// Mark the current bisect commit as good.
        BisectGood unbound if is_bisecting;
        /// Mark the current bisect commit as bad.
        BisectBad unbound if is_bisecting;
        /// End the bisect session and restore HEAD.
        BisectReset unbound if is_bisecting;
        /// Skip the current bisect commit.
        BisectSkip unbound if is_bisecting;
        /// Search the contents of the working tree.
        GlobalSearch unbound;
        /// Toggle the issues panel.
        ToggleIssues "alt-5";
        /// Toggle the pull requests panel.
        TogglePullRequests "alt-6";
        /// Toggle the branch health panel.
        ToggleBranchHealth "alt-7";
        /// Toggle the stashes panel.
        ToggleStashes "alt-8";
        /// Create a branch from a stash entry.
        StashBranch unbound if has_stashes;
        /// Open the theme editor.
        OpenThemeEditor ["secondary-shift-t", "alt-9"] in "Workspace";
        /// Toggle the command palette.
        CommandPalette "secondary-shift-p" in "Workspace" [hidden];
        /// Activate the next repository tab.
        NextTab "secondary-tab" [hidden];
        /// Activate the previous repository tab.
        PrevTab "secondary-shift-tab" [hidden];
        /// Close the active repository tab.
        CloseTab "secondary-w" [hidden];
    }
}

impl CommandId {
    /// Static metadata for this command.
    pub fn meta(self) -> &'static CommandMeta {
        ALL_COMMANDS
            .iter()
            .find(|meta| meta.id == self)
            // Unreachable: `ALL_COMMANDS` and `CommandId` are generated together.
            .expect("every CommandId has metadata")
    }

    /// The key context the default bindings for this command are scoped to.
    pub fn context(self) -> &'static str {
        self.meta().context
    }

    /// This command's default keystrokes, or an empty slice when it has none.
    pub fn default_keystrokes(self) -> &'static [&'static str] {
        self.meta().default_keystrokes
    }

    /// A one-line description of what this command does.
    pub fn description(self) -> &'static str {
        self.meta().description()
    }

    /// Whether this command is offered in the command palette.
    pub fn in_palette(self) -> bool {
        self.meta().in_palette
    }

    /// The command-palette availability predicate for this command.
    pub fn availability(self) -> fn(CommandContext) -> bool {
        self.meta().availability
    }
}

impl std::fmt::Display for CommandId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl TryFrom<&str> for CommandId {
    type Error = ();

    fn try_from(value: &str) -> Result<Self, Self::Error> {
        CommandId::ALL
            .iter()
            .copied()
            .find(|id| id.as_str() == value)
            .ok_or(())
    }
}

/// Looks up a command by its gpui action name (`namespace::Name`).
pub fn command_for_action(action_name: &str) -> Option<CommandId> {
    ALL_COMMANDS
        .iter()
        .find(|meta| meta.action_name == action_name)
        .map(|meta| meta.id)
}

