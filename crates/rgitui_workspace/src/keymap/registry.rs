    #[test]
    fn command_id_strings_are_stable() {
        for (id, expected) in LEGACY_IDS {
            assert_eq!(id.as_str(), *expected, "as_str drifted for {id:?}");
        }
    }

    #[test]
    fn command_ids_round_trip_through_strings() {
        for id in CommandId::ALL {
            assert_eq!(
                CommandId::try_from(id.as_str()),
                Ok(*id),
                "{id:?} did not round-trip"
            );
        }
        assert_eq!(CommandId::try_from("not_a_command"), Err(()));
    }

    #[test]
    fn command_ids_are_unique() {
        let ids: HashSet<&str> = CommandId::ALL.iter().map(|id| id.as_str()).collect();
        assert_eq!(ids.len(), CommandId::ALL.len());
    }

    #[test]
    fn registry_covers_every_command() {
        assert_eq!(ALL_COMMANDS.len(), CommandId::ALL.len());
        for (meta, id) in ALL_COMMANDS.iter().zip(CommandId::ALL) {
            assert_eq!(meta.id, *id);
        }
    }

    #[test]
    fn action_names_are_namespaced_and_unique() {
        let mut names = HashSet::new();
        for meta in ALL_COMMANDS {
            assert!(
                meta.action_name
                    .starts_with(&format!("{}::", meta.namespace)),
                "{} is not namespaced",
                meta.action_name
            );
            let bare = meta
                .action_name
                .trim_start_matches(&format!("{}::", meta.namespace));
            assert!(
                !bare.contains("::"),
                "gpui panics on action names containing `::`: {}",
                meta.action_name
            );
            assert!(
                names.insert(meta.action_name),
                "duplicate {}",
                meta.action_name
            );
            assert_eq!(command_for_action(meta.action_name), Some(meta.id));
        }
    }

    /// Guards the runtime path: `keymap.json` resolves actions by name through
    /// `App::build_action`, which only knows the actions gpui collected from the
    /// `inventory` registry at link time. If the generated structs were ever
    /// dropped by the linker every binding would silently fail to load.
    #[test]
    fn every_action_is_registered_with_gpui() {
        let registered: HashSet<&str> = gpui::generate_list_of_all_registered_actions()
            .map(|action| action.name)
            .collect();
        for meta in ALL_COMMANDS {
            assert!(
                registered.contains(meta.action_name),
                "{} is not registered with gpui, so keymap.json could not name it",
                meta.action_name
            );
        }
    }

    /// The doc comment on each command becomes the action's `documentation()`,
    /// which is what a future keybinding editor would show.
    #[test]
    fn action_documentation_comes_from_the_doc_comment() {
        let documented: Vec<(&str, Option<&str>)> = gpui::generate_list_of_all_registered_actions()
            .map(|action| (action.name, action.documentation))
            .collect();
        for meta in ALL_COMMANDS {
            let (_, documentation) = documented
                .iter()
                .find(|(name, _)| *name == meta.action_name)
                .expect("every action is registered");
            assert_eq!(
                *documentation,
                Some(meta.description()),
                "{} documentation drifted from its doc comment",
                meta.action_name
            );
        }
    }

    #[test]
    fn every_command_is_documented() {
        for meta in ALL_COMMANDS {
            assert!(
                !meta.description().is_empty(),
                "{} has no doc comment",
                meta.action_name
            );
        }
    }

    #[test]
    fn hidden_commands_are_the_ones_absent_from_the_palette() {
        let palette: HashSet<CommandId> = crate::command_palette::palette_commands()
            .iter()
            .map(|command| command.id)
            .collect();
        for meta in ALL_COMMANDS {
            assert_eq!(
                palette.contains(&meta.id),
                meta.in_palette,
                "{} palette membership disagrees with the `[hidden]` marker",
                meta.action_name
            );
        }
    }

    #[test]
    fn palette_predicates_match_the_registry() {
        for command in crate::command_palette::palette_commands() {
            let expected = command.id.availability();
            assert!(
                std::ptr::fn_addr_eq(command.predicate(), expected),
                "{} availability predicate disagrees with the registry",
                command.id
            );
        }
    }
